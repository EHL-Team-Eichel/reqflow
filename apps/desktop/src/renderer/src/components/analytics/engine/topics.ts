/** Lowercase, accents and umlauts removed (ä → a), ß → ss, any run of non-letters → one space. */
export function foldForTopics(s: string): string {
  return s
    .toLowerCase()
    .replace(/ß/g, "ss")
    .normalize("NFKD")
    .replace(/\p{M}+/gu, "")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** One regex per topic: an alternation of its keywords, whole words, `*` = longer word allowed. */
const COMPILED: readonly { id: string; re: RegExp }[] = TOPICS.map((topic) => {
  const parts = topic.keywords.map((keyword) => {
    const prefix = keyword.endsWith("*");
    const words = foldForTopics(prefix ? keyword.slice(0, -1) : keyword).split(" ");
    return words.map(escape).join(" ") + (prefix ? "\\p{L}*" : "");
  });
  return {
    id: topic.id,
    re: new RegExp(`(?<![\\p{L}\\p{N}])(?:${parts.join("|")})(?![\\p{L}\\p{N}])`, "u"),
  };
});

const LABELS = new Map(TOPICS.map((t) => [t.id, t.label]));
const GROUPS = new Map(TOPICS.map((t) => [t.id, t.group]));

/** Ids of the topics the text mentions, in TOPICS order. */
export function topicsOf(text: string): string[] {
  const folded = foldForTopics(text);
  if (!folded) return [];
  return COMPILED.filter((t) => t.re.test(folded)).map((t) => t.id);
}

export function topicLabel(id: string): string {
  return LABELS.get(id) ?? id;
}

export function topicGroup(id: string): TopicGroup | undefined {
  return GROUPS.get(id);
}
