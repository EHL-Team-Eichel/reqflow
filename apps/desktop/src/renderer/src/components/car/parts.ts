import type { RequirementCategory } from "@reqflow/core";
import { COMPONENT_PARTS } from "./componentParts";

/**
 * The clickable parts of the car on the Car tab. Every part has at least one mesh in the 3D model
 * (`model/buildCar.ts`, checked by a test) and the vocabulary the auto classifier uses to put a
 * requirement on it (`classify.ts`).
 *
 * Keywords are whole-word, case-insensitive regex fragments in English and German (BMW's feedback
 * comes in both). Longer matches win over shorter ones on the same words, so "rear seats" goes to
 * the rear seats and never also counts as "seats" for the front seats.
 */
export type PartGroup = "exterior" | "interior" | "technology";

export interface CarPart {
  id: string;
  label: string;
  group: PartGroup;
  /** One line on what a customer experiences here; shown when the part is selected. */
  blurb: string;
  keywords: string[];
  /** Categories that make this part a likely home. Only used to break ties and as a last resort. */
  categories?: RequirementCategory[];
}

