type FactorInput = Record<ScoreFactor, { value: number; note: string }>;

/** Scores exactly as prioritization.score would: documented formula + DEFAULT_SETTINGS snapshot. */
function scoreWith(factors: FactorInput): ScoreBreakdown {
  const { weights, thresholds } = DEFAULT_SETTINGS.scoring;
  const values = Object.fromEntries(
    ScoreFactor.options.map((f) => [f, factors[f].value]),
  ) as Record<ScoreFactor, number>;
  const total = weightedTotal(values, weights);
  return {
    factors: Object.fromEntries(
      ScoreFactor.options.map((f) => [f, { ...factors[f], weight: weights[f] }]),
    ) as ScoreBreakdown["factors"],
    total,
    suggestedPriority: priorityForScore(total, thresholds),
    method: "weighted-sum@1",
    scoredAt: "2026-10-10T08:59:00.000Z",
  };
}

